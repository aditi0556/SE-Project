from google.adk.agents import Agent
from google.adk.tools.mcp_tool import McpToolset
from google.adk.tools.mcp_tool.mcp_session_manager import StdioConnectionParams
from mcp import StdioServerParameters
from pydantic import BaseModel, Field
from typing import List
from config import get_model
from google.adk.models.lite_llm import LiteLlm
import os 
QDRANT_URL = "http://localhost:6333"
COLLECTION_NAME = "healthcare_knowledge"


class RequirementVerification(BaseModel):
    requirement: str = Field(
        description="The functional or non-functional requirement being verified"
    )
    status: str = Field(
        description="Verification status: Compliant, Non-Compliant, Partially Compliant, or Not Covered in Healthcare DB"
    )
    retrieved_evidence: str = Field(
        description="Relevant evidence or guidelines retrieved from healthcare_db.pdf via Qdrant"
    )
    notes: str = Field(
        description="Compliance verification notes or recommendations based on the retrieved healthcare knowledge"
    )


class ComplianceOutput(BaseModel):
    verified_requirements: List[RequirementVerification] = Field(
        description="Verification details for each functional and non-functional requirement"
    )
    summary: str = Field(
        description="Brief summary of the requirement compliance verification against healthcare_db.pdf"
    )


qdrant_tools = McpToolset(
    connection_params=StdioConnectionParams(
        server_params=StdioServerParameters(
            command="/home/aditi-sinha/.local/bin/uvx",
            args=["mcp-server-qdrant"],
            env={
                "PATH": "/home/aditi-sinha/.local/bin:/usr/local/bin:/usr/bin:/bin",
                "QDRANT_URL": QDRANT_URL,
                "COLLECTION_NAME": COLLECTION_NAME,
            },
        ),
        timeout=30,
    ),
)

compliance_agent = Agent(
    name="compliance_agent",
    model="gemini-3.5-flash-lite",
    # model=LiteLlm(
    #     model="openrouter/qwen/qwen3.8-27b",
    #     api_key=os.environ["OPENROUTER_API_KEY"],
    #     api_base="https://openrouter.ai/api/v1",
    #     max_tokens=4096,
    # ),
    description=(
        "Verifies every requirement generated by the Requirement Analyser "
        "against the healthcare knowledge base in Qdrant (healthcare_db.pdf)."
    ),
    instruction="""
        You are a Compliance Agent for healthcare software.

        The Requirement Analyser has generated functional and non-functional requirements, available in session state under `requirements`.

        Your task is to verify EVERY requirement against the healthcare knowledge base in Qdrant (`healthcare_knowledge`), indexed from `healthcare_db.pdf`.

    1. Retrieve Knowledge:
       Use the Qdrant retrieval tool with 1 or 2 focused queries to search 'healthcare_knowledge'
       for relevant healthcare domain rules, standards (e.g. FHIR, medical device safety),
       and guidelines covering the requirements. Do not execute separate queries for every individual requirement.

        Do not skip requirements, invent external regulations or unsupported rules, or mark a requirement Non-Compliant without explicit contradictory evidence.

        Do NOT modify requirements or recommend an SDLC model.

        Return ONLY the structured output.
    """,
    tools=[qdrant_tools],
    output_schema=ComplianceOutput,
    output_key="compliance",
)
